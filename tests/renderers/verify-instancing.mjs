// Run against a local Vite development server: node tests/renderers/verify-instancing.mjs http://127.0.0.1:5175
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from '@playwright/test';
const base = process.argv[2] ?? 'http://127.0.0.1:5175';
await mkdir('test-results', { recursive: true });
const browser = await chromium.launch({ args: ['--enable-unsafe-swiftshader'] });
try {
  for (const kind of ['block', 'slice']) {
    const page = await browser.newPage({ viewport: { width: 1000, height: 700 } });
    const errors = [];
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('console', (message) => {
      // SwiftShader's screenshot readback diagnostic is generated by Chromium, not the app.
      if (
        ['error', 'warning'].includes(message.type()) &&
        !message.text().includes('GPU stall due to ReadPixels')
      )
        errors.push(message.text());
    });
    await page.goto(`${base}/tests/renderers/instancingHarness.html?kind=${kind}`);
    await page
      .waitForFunction(() => !!window.rendererProbe?.point(0), undefined, { timeout: 15000 })
      .catch(async (error) => {
        console.error(errors, await page.locator('body').innerText());
        throw error;
      });
    const point = await page.evaluate(() => window.rendererProbe.point(0));
    assert(point);
    await page.mouse.move(point.x, point.y);
    await page
      .waitForFunction(
        () =>
          document.querySelector('[data-selection]')?.getAttribute('data-selection') === 'symbol-0',
        undefined,
        { timeout: 5000 },
      )
      .catch(async (error) => {
        console.error({
          kind,
          point,
          selection: await page.locator('[data-selection]').getAttribute('data-selection'),
          errors,
        });
        await page.screenshot({ path: `test-results/renderer-${kind}-failed.png` });
        throw error;
      });
    await page.mouse.click(point.x, point.y);
    await page.waitForFunction(
      () => document.querySelector('[data-active]')?.getAttribute('data-active') === 'part-0',
    );
    const hit = await page.evaluate(() => window.rendererProbe.hit());
    assert.equal(hit?.entityId, 'part-0');
    assert(hit.p.every(Number.isFinite));
    assert(
      Math.abs(hit.p[0]) < 1 && Math.abs(hit.p[2]) < 1,
      'Hit remains in original entity-local units.',
    );
    await page.screenshot({ path: `test-results/renderer-${kind}-before.png` });
    await page.evaluate(() => window.rendererProbe.update());
    await page.waitForFunction(
      () => Number(document.querySelector('canvas')?.getAttribute('data-render-calls')) > 0,
    );
    await page.mouse.click(point.x, point.y);
    assert.notEqual(
      await page.locator('[data-active]').getAttribute('data-active'),
      'part-0',
      'A zero-opacity instance cannot activate.',
    );
    const counts = await page.locator('canvas').evaluate((canvas) => ({
      calls: Number(canvas.dataset.renderCalls),
      triangles: Number(canvas.dataset.renderTriangles),
    }));
    assert(counts.calls <= 150, `${kind}: ${counts.calls} draw calls exceed the budget.`);
    assert(counts.triangles <= 200000, `${kind}: ${counts.triangles} triangles exceed the budget.`);
    await page.screenshot({ path: `test-results/renderer-${kind}-after.png` });
    const before = await page.locator('canvas').getAttribute('data-camera-position');
    await page.evaluate(() => window.rendererProbe.hold(true));
    await page.mouse.move(500, 300);
    await page.mouse.down();
    await page.mouse.move(550, 320, { steps: 6 });
    await page.mouse.up();
    assert.equal(
      await page.locator('canvas').getAttribute('data-camera-position'),
      before,
      'Hold pauses camera controls.',
    );
    await page.evaluate(() => window.rendererProbe.hold(false));
    assert.deepEqual(errors, [], 'Renderer has no console warnings, errors, or shader failures.');
    console.log(
      `${kind}: 96 instances, ${counts.calls} draw calls, ${counts.triangles} triangles; stable hits, hidden-instance rejection, paused camera, no console errors.`,
    );
    await page.close();
  }
} finally {
  await browser.close();
}
